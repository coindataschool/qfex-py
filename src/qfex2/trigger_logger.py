"""
Writes one JSONL record per successfully-ACKed STOP_LOSS/TAKE_PROFIT
placement — the trigger_price, order_id, side, and label (which leg it
is) are all known with certainty at this point in the code, unlike
trying to recover them after the fact from QFEX's historic-orders/trade
endpoints (which collapse both legs into an indistinguishable
STOP_MARKET execution type — see markout/slippage analysis discussion).

Logged on ACK, not on placement attempt — this records what actually
ended up armed on the exchange, not every retry/timeout/rejection
attempt (those are still fully visible in the existing log.info/
log.warning/log.error calls already at this call site; this file is
additive, not a replacement for those).

Output is later joined against reconstructed trips
(fetch_and_reconstruct_trips.py) via order_id: each Trip's exit_trade
likely has an order_id belonging to a STOP_MARKET execution that was
GENERATED BY one of these ACKed stop orders triggering — NOT the same
order_id as the ACK itself. Confirming exactly how the two order_ids
relate (same id reused, or a new id minted at trigger time) is the
first thing to check once real data exists; this logger doesn't assume
an answer to that, it just records everything known at ACK time so the
join can be figured out empirically.
"""

import json
import threading
from decimal import Decimal
from pathlib import Path
from typing import Optional


class TriggerLogger:
    """
    One line-buffered JSONL append per ACKed stop-order placement.
    Thread-safety note: qfex2 is asyncio-based, single-threaded per
    event loop, so the lock below is defensive rather than strictly
    required given current usage — cheap to keep, avoids a subtle bug
    if this ever gets called from more than one task concurrently.
    """

    def __init__(self, out_path: str = "trigger_log.jsonl"):
        self.out_path = Path(out_path)
        self.out_path.parent.mkdir(parents=True, exist_ok=True)
        self._fh = open(self.out_path, "a")
        self._lock = threading.Lock()

    def log_trigger_ack(
        self,
        *,
        label: str,  # "STOP_LOSS" or "TAKE_PROFIT"
        symbol: str,
        exit_side: str,  # str(Side) — the exit order's side, not the
                          # position's side (matches _place_one_stop_leg's
                          # own exit_side param)
        order_id: Optional[str],
        client_order_id: Optional[str],
        trigger_price: Decimal,
        exit_qty: Decimal,
        average_price: Decimal,  # position's average_price at the time
                                  # this leg was armed — needed later to
                                  # compute realized slippage AND to
                                  # confirm which leg is SL vs TP
                                  # independent of the `label` field
                                  # (cross-check: trigger should be below
                                  # average_price for a long's SL, above
                                  # for its TP)
        ts: float,
    ) -> None:
        record = {
            "ts": ts,
            "label": label,
            "symbol": symbol,
            "exit_side": exit_side,
            "order_id": order_id,
            "client_order_id": client_order_id,
            "trigger_price": str(trigger_price),
            "exit_qty": str(exit_qty),
            "average_price": str(average_price),
        }
        with self._lock:
            self._fh.write(json.dumps(record) + "\n")
            self._fh.flush()

    def close(self) -> None:
        self._fh.close()
